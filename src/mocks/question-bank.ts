function pct(remaining: number, total: number): HealthStatus {
  const p = (remaining / total) * 100;
  if (p <= 5) return "Critical";
  if (p <= 20) return "Warning";
  return "Healthy";
}

function makeOptions(texts: string[]): AnswerOption[] {
  return texts.map((text, i) => ({ id: `opt-${i + 1}`, text }));
}

